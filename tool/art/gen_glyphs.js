#!/usr/bin/env node
// Extracts the icon art of the artboards (arrays built with `P(d, fill, stroke,
// width)`) into lib/core/art/glyph_icons.dart.
//
//   node tool/art/gen_glyphs.js
//
// Why a generator: the boards are the spec; porting their path data by script
// (rather than retyping) keeps every curve identical. The script evaluates each
// board's <script> block in a sandbox, reads the named constants and writes
// them as const `Glyph`s. Hand-made icons that no board defines live in
// glyph_extras.dart.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const dir = path.join(__dirname, '..', '..', 'design', 'artboards', 'project');

function load(file) {
  const html = fs.readFileSync(path.join(dir, file), 'utf8');
  const m = /<script type="text\/x-dc" data-dc-script[^>]*>([\s\S]*?)<\/script>/.exec(html);
  // Expose top-level consts, and drop the component class (it needs the DC runtime).
  const src = m[1].replace(/^const (\w+) =/gm, 'globalThis.$1 =').replace(/^class Component[\s\S]*$/m, '');
  const ctx = { console, Math, Array, Object, JSON, String, Number };
  ctx.globalThis = ctx;
  vm.runInNewContext(src, ctx, { timeout: 2000 });
  return ctx;
}

const GRAD = { gGold: 'gold', gRed: 'red', gClay: 'clay', gPurple: 'purple', gPhone: 'phone', gWood: 'wood' };
const color = (v) => '0xFF' + /^#([0-9a-f]{6})$/i.exec(v)[1].toUpperCase();
const BACKSLASH = String.fromCharCode(92);
const q = (s) => "'" + s.split(BACKSLASH).join(BACKSLASH + BACKSLASH).split("'").join(BACKSLASH + "'") + "'";
const num = (n) => (Number.isInteger(n) ? String(n) + '.0' : String(n));

function part(p) {
  const args = [q(p.d)];
  const g = /^url\(#(\w+)\)$/.exec(p.f);
  if (g) args.push('gradient: GlyphGradient.' + GRAD[g[1]]);
  else if (p.f && p.f !== 'none') args.push('fill: Color(' + color(p.f) + ')');
  if (p.s && p.s !== 'none') {
    args.push('stroke: Color(' + color(p.s) + ')');
    args.push('strokeWidth: ' + num(p.w));
  }
  return 'GlyphPart(' + args.join(', ') + ')';
}

function glyph(parts, box) {
  return 'Glyph(box: ' + box + ', [\n' + parts.map((p) => '    ' + part(p) + ',').join('\n') + '\n  ])';
}

const out = [];
const seen = new Set();
function add(name, doc, parts, box) {
  if (seen.has(name)) throw new Error('duplicate ' + name);
  seen.add(name);
  out.push('  /// ' + doc);
  out.push('  static const ' + name + ' = ' + glyph(parts, box) + ';');
  out.push('');
}

const main = load('Main.dc.html');
for (const k of ['coins', 'wheel', 'gift', 'missions']) add('stall' + k[0].toUpperCase() + k.slice(1), 'Lobby stall icon "' + k + '" (Main.dc.html ICONS).', main.ICONS[k], 24);
for (const k of ['pass', 'wifi', 'mayhem', 'puzzle']) add('mode' + k[0].toUpperCase() + k.slice(1), 'Lobby mode tile art "' + k + '" (Main.dc.html ART, 48 box).', main.ART[k], 48);
for (const k of ['home', 'friends', 'collection', 'road', 'events']) add('dock' + k[0].toUpperCase() + k.slice(1), 'Round-dock tab icon "' + k + '" (Main.dc.html NAV).', main.NAV[k], 24);

const col = load('Collection.dc.html');
add('tabDice', 'Collection tab: dice (32 box).', col.TAB_ICONS.dice, 32);
add('tabPieces', 'Collection tab: pieces (32 box).', col.TAB_ICONS.pucks, 32);
add('tabBoards', 'Collection tab: boards (32 box).', col.TAB_ICONS.boards, 32);

const earn = load('Earn.dc.html');
add('coinStack', 'Two stacked coins (Earn.dc.html, 32 box).', earn.COINS, 32);
add('gemCluster', 'A cut gem (Earn.dc.html, 32 box).', earn.GEMS, 32);
add('potClay', 'The clay Mela pot with a purple cloth (Earn.dc.html CHEST, 32 box).', earn.CHEST, 32);

const vs = load('VsAiSetup.dc.html');
for (const m of vs.MODES) add('rule' + m.id[0].toUpperCase() + m.id.slice(1), 'Game mode icon "' + m.id + '" (VsAiSetup.dc.html, 32 box).', m.icon, 32);

const match = load('Match.dc.html');
for (const k of ['happy', 'laugh', 'wow', 'cool', 'angry', 'cry']) add('sticker' + k[0].toUpperCase() + k.slice(1), 'Sticker face "' + k + '" (Match.dc.html).', match.sticker(k), 24);

const head = [
  '// GENERATED by tool/art/gen_glyphs.js from the artboards — do not edit by hand.',
  '//',
  '// Icon art of the design boards as const [Glyph]s: lobby stall icons, mode tile art,',
  '// round-dock icons, collection tabs, the coin / gem / pot illustrations and the',
  '// sticker faces. Hand-made icons live in glyph_extras.dart.',
  '',
  "import 'dart:ui' show Color;",
  '',
  "import 'glyph.dart';",
  '',
  '/// The icon set ported from the artboards.',
  'abstract final class LmGlyphs {',
];
const target = path.join(__dirname, '..', '..', 'lib', 'core', 'art', 'glyph_icons.dart');
fs.writeFileSync(target, head.concat(out, ['}', '']).join('\n'));
console.log('wrote ' + target + ' (' + seen.size + ' glyphs)');
