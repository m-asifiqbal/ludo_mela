#!/usr/bin/env node
// Converts design/tools/avatars.js (the animal-avatar source of truth shared by
// every artboard) into lib/core/art/avatar_data.dart.
//
//   node tool/art/gen_avatars.js
//
// Why a generator: the artboards are the spec, so the Flutter data must be
// derived from the very same file, never retyped. Re-run it whenever
// design/tools/avatars.js changes; the output is deterministic.
const fs = require('fs');
const path = require('path');

const { ANIMALS, AV_OF, NAMES } = require(path.join(__dirname, '..', '..', 'design', 'tools', 'avatars.js'));

/** '#RRGGBB' | 'rgba(r,g,b,a)' | 0 → Dart ARGB literal (or null for "none"). */
function argb(v) {
  if (!v) return null;
  let m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) return '0xFF' + m[1].toUpperCase();
  m = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/i.exec(v);
  if (m) {
    const a = Math.round(parseFloat(m[4]) * 255);
    const h = (n) => Number(n).toString(16).toUpperCase().padStart(2, '0');
    return '0x' + h(a) + h(m[1]) + h(m[2]) + h(m[3]);
  }
  throw new Error('unsupported colour ' + v);
}

const ANIM = { blink: 'AvatarAnim.blink', earl: 'AvatarAnim.earLeft', earr: 'AvatarAnim.earRight' };
const BACKSLASH = String.fromCharCode(92);
const q = (s) => "'" + s.split(BACKSLASH).join(BACKSLASH + BACKSLASH).split("'").join(BACKSLASH + "'") + "'";

function part(p) {
  const [d, fill, stroke, width, anim, origin] = p;
  const args = [q(d)];
  const f = argb(fill);
  const s = argb(stroke);
  if (f) args.push('fill: ' + f);
  if (s) args.push('stroke: ' + s);
  if (width) args.push('strokeWidth: ' + width);
  if (anim) {
    args.push('anim: ' + ANIM[anim]);
    const [ox, oy] = origin.split(' ').map((v) => parseFloat(v));
    args.push('ox: ' + ox, 'oy: ' + oy);
  }
  return '    AvatarPart(' + args.join(', ') + '),';
}

const out = [];
out.push('// GENERATED by tool/art/gen_avatars.js from design/tools/avatars.js — do not edit by hand.');
out.push('//');
out.push('// The animal avatar cast (48 x 48 vector boxes): ' + Object.keys(ANIMALS).join(', ') + '.');
out.push('// Parts are painted in order over a flat background colour; parts tagged');
out.push('// with an [AvatarAnim] blink or wiggle around their (ox, oy) origin.');
out.push('');
out.push("import 'avatar_part.dart';");
out.push('');
out.push('/// Every animal (and the stock "photo" placeholder) by id.');
out.push('const Map<String, AvatarArt> kAvatarArt = {');
for (const id of Object.keys(ANIMALS)) {
  const [bg, parts] = ANIMALS[id];
  out.push("  '" + id + "': AvatarArt(");
  out.push('    background: ' + argb(bg) + ',');
  out.push('    parts: [');
  for (const p of parts) out.push(part(p.map((v) => (v === undefined ? 0 : v))));
  out.push('    ],');
  out.push('  ),');
}
out.push('};');
out.push('');
out.push('/// Character / bot / family-player name → animal id (e.g. `raja` → tiger).');
out.push('const Map<String, String> kAvatarOf = {');
for (const [k, v] of Object.entries(AV_OF)) out.push("  '" + k + "': '" + v + "',");
out.push('};');
out.push('');
out.push('/// Display names of the animals ("Mishti the cat").');
out.push('const Map<String, String> kAvatarNames = {');
for (const [k, v] of Object.entries(NAMES)) out.push("  '" + k + "': " + q(v) + ',');
out.push('};');
out.push('');

const target = path.join(__dirname, '..', '..', 'lib', 'core', 'art', 'avatar_data.dart');
fs.writeFileSync(target, out.join('\n'));
console.log('wrote ' + target + ' (' + Object.keys(ANIMALS).length + ' avatars)');
